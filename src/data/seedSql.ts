import type { CheckIn, Member } from './types.ts'

/** Rows per INSERT statement, to keep each statement a manageable size. */
const ROWS_PER_INSERT = 500

type SqlValue = string | number | boolean | null

/** Writes one value as a SQL literal, escaping quotes in text. */
export function toSqlLiteral(value: SqlValue) {
  if (value === null) return 'null'
  if (typeof value === 'string') return `'${value.replaceAll("'", "''")}'`
  return String(value)
}

/** Builds INSERT statements for a table, a batch of rows at a time. */
function insertInto(table: string, columns: string[], rows: SqlValue[][]) {
  const statements: string[] = []
  for (let start = 0; start < rows.length; start += ROWS_PER_INSERT) {
    const values = rows
      .slice(start, start + ROWS_PER_INSERT)
      .map((row) => `  (${row.map(toSqlLiteral).join(', ')})`)
      .join(',\n')
    statements.push(
      `insert into public.${table} (${columns.join(', ')}) values\n${values};`,
    )
  }
  return statements.join('\n\n')
}

/**
 * Builds the SQL that fills the database with the given members and
 * check-ins. It empties the three tables first, so running it again
 * replaces the data instead of duplicating it.
 */
export function buildSeedSql(members: Member[], checkIns: CheckIn[]) {
  const memberRows = members.map((m): SqlValue[] => [
    m.id,
    m.name,
    m.dateOfBirth,
    m.membershipType,
    m.membershipStartDate,
    m.frozenFrom,
    m.frozenTo,
    m.cancelledAt,
    m.membershipEndDate,
    m.cancellationReason,
    m.price,
    m.failedPaymentCount,
    m.acquisitionSource,
    m.dayPassVisitsBeforeJoining,
    m.tookIntroClass,
    m.hadOrientation,
    m.belayTestPassedOn,
    m.ownsShoes,
    m.ownsHarness,
    m.experienceLevel,
    m.preferredDiscipline,
    m.maxGrade,
    m.projectGrade,
    m.heightCm,
    m.gender,
    m.mainGoal,
    m.postalArea,
  ])
  const previousRows = members.flatMap((m) =>
    m.previousMemberships.map((past): SqlValue[] => [
      m.id,
      past.membershipType,
      past.startDate,
      past.endDate,
    ]),
  )
  const checkInRows = checkIns.map((c): SqlValue[] => [
    c.id,
    c.memberId,
    c.checkedInAt,
  ])

  const sections = [
    '-- Generated by `npm run seed:generate`. Do not edit by hand.',
    `-- ${members.length} members, ${previousRows.length} previous memberships, ${checkIns.length} check-ins.`,
    'begin;',
    'truncate table public.check_ins, public.previous_memberships, public.members\n  restart identity;',
    insertInto(
      'members',
      [
        'id',
        'name',
        'date_of_birth',
        'membership_type',
        'membership_start_date',
        'frozen_from',
        'frozen_to',
        'cancelled_at',
        'membership_end_date',
        'cancellation_reason',
        'price',
        'failed_payment_count',
        'acquisition_source',
        'day_pass_visits_before_joining',
        'took_intro_class',
        'had_orientation',
        'belay_test_passed_on',
        'owns_shoes',
        'owns_harness',
        'experience_level',
        'preferred_discipline',
        'max_grade',
        'project_grade',
        'height_cm',
        'gender',
        'main_goal',
        'postal_area',
      ],
      memberRows,
    ),
    insertInto(
      'previous_memberships',
      ['member_id', 'membership_type', 'start_date', 'end_date'],
      previousRows,
    ),
    insertInto('check_ins', ['id', 'member_id', 'checked_in_at'], checkInRows),
    'commit;',
  ]
  return sections.filter((section) => section !== '').join('\n\n') + '\n'
}
